$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$bitmap = New-Object Drawing.Bitmap 256,256
$graphics = [Drawing.Graphics]::FromImage($bitmap)
$graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
$outline = New-Object Drawing.Drawing2D.GraphicsPath
$outline.AddArc(8,8,64,64,180,90)
$outline.AddArc(184,8,64,64,270,90)
$outline.AddArc(184,184,64,64,0,90)
$outline.AddArc(8,184,64,64,90,90)
$outline.CloseFigure()
$background = New-Object Drawing.SolidBrush ([Drawing.Color]::FromArgb(24,36,51))
$graphics.FillPath($background,$outline)
$trayBrush = New-Object Drawing.SolidBrush ([Drawing.Color]::FromArgb(58,81,99))
$graphics.FillRectangle($trayBrush,37,172,182,20)
$tileBrush = New-Object Drawing.SolidBrush ([Drawing.Color]::FromArgb(133,216,199))
$graphics.FillRectangle($tileBrush,43,128,32,36)
$graphics.FillRectangle($tileBrush,86,101,36,63)
$graphics.FillRectangle($tileBrush,133,78,42,86)
$graphics.FillRectangle($tileBrush,186,128,27,36)
$graphics.Dispose()
$png = New-Object IO.MemoryStream
$bitmap.Save($png,[Drawing.Imaging.ImageFormat]::Png)
$destination = [IO.File]::Create((Join-Path $PSScriptRoot 'app.ico'))
$writer = New-Object IO.BinaryWriter $destination
$writer.Write([UInt16]0)
$writer.Write([UInt16]1)
$writer.Write([UInt16]1)
$writer.Write([Byte]0)
$writer.Write([Byte]0)
$writer.Write([Byte]0)
$writer.Write([Byte]0)
$writer.Write([UInt16]1)
$writer.Write([UInt16]32)
$writer.Write([UInt32]$png.Length)
$writer.Write([UInt32]22)
$writer.Write($png.ToArray())
$writer.Dispose()
$png.Dispose()
$bitmap.Dispose()
$background.Dispose()
$trayBrush.Dispose()
$tileBrush.Dispose()
$outline.Dispose()
